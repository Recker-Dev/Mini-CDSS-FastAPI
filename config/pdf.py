"""Render a report (markdown) into a styled PDF, backend-side.

Minimalist, modern, warm-toned template (a nod to Claude's palette): warm paper,
clay accent, quiet typographic hierarchy. Pure-Python (xhtml2pdf + markdown), so
no system libraries are needed in the image.
"""
import datetime
import re
from io import BytesIO

import markdown as md
from xhtml2pdf import pisa

# Emoji / pictographs: the built-in PDF fonts can't render them, so strip for a
# clean, professional document (the prompts sprinkle 📌🧠✅🩺🔗📖 etc.).
# Also consume inline spaces that follow (but not newlines), so that
# "**📌 Heading**" collapses to "**Heading**" and stays bold in markdown.
_EMOJI_RE = re.compile(
    "[\U0001F000-\U0001FAFF\U00002600-\U000027BF\U0001F1E6-\U0001F1FF"
    "\U00002190-\U000021FF\U00002B00-\U00002BFF\U0000FE00-\U0000FE0F\U00002700-\U000027BF]+[ \t]*",
    flags=re.UNICODE,
)


def _strip_emoji(text: str) -> str:
    return _EMOJI_RE.sub("", text)


_TEMPLATE = """<!DOCTYPE html>
<html><head><meta charset="utf-8"><style>
@page {{
    size: a4;
    margin: 2.4cm 2cm 2.2cm 2cm;
    @frame footer_frame {{
        -pdf-frame-content: footerContent;
        bottom: 1.1cm; left: 2cm; right: 2cm; height: 1cm;
    }}
}}
body {{ font-family: Helvetica; font-size: 10.5pt; color: #3d3b36; line-height: 1.5; }}

.header {{ background-color: #f7f3ee; border-left: 3pt solid #c96442;
          padding: 12pt 14pt; margin-bottom: 4pt; }}
.brand {{ font-size: 8pt; letter-spacing: 2pt; color: #c96442; font-weight: bold; }}
.title {{ font-size: 19pt; color: #2b2a27; font-weight: bold; padding-top: 2pt; }}
.meta  {{ font-size: 8.5pt; color: #928b7e; padding-top: 4pt; }}
.rule  {{ border: none; border-top: 0.75pt solid #e8e0d5; margin: 14pt 0 10pt 0; }}

h2 {{ font-size: 13.5pt; color: #c96442; font-weight: bold;
      border-bottom: 0.75pt solid #ede5da; padding-bottom: 3pt;
      margin-top: 18pt; margin-bottom: 7pt; }}
h3 {{ font-size: 11.5pt; color: #2b2a27; font-weight: bold;
      margin-top: 12pt; margin-bottom: 4pt; }}
h4 {{ font-size: 10.5pt; color: #4a4843; font-weight: bold; margin-top: 9pt; }}
p  {{ margin: 4pt 0; }}
ul, ol {{ margin: 4pt 0 4pt 2pt; }}
li {{ margin-bottom: 3pt; }}
a  {{ color: #c96442; text-decoration: none; }}
strong, b {{ color: #2b2a27; }}
hr {{ border: none; border-top: 0.75pt solid #e8e0d5; margin: 10pt 0; }}

#footerContent {{ font-size: 7.5pt; color: #a9a295; border-top: 0.5pt solid #ede5da;
                  padding-top: 4pt; }}
.disclaimer {{ font-style: italic; }}
</style></head>
<body>
    <div class="header">
        <div class="brand">MINI-CDSS</div>
        <div class="title">{title}</div>
        <div class="meta">{subtitle}Generated {generated_on}</div>
    </div>
    <hr class="rule"/>

    {content}

    <div id="footerContent">
        <span class="disclaimer">Generated by Mini-CDSS — a decision-support aid, not a substitute for clinical judgement.</span>
        &nbsp;&nbsp;·&nbsp;&nbsp; Page <pdf:pagenumber> of <pdf:pagecount>
    </div>
</body></html>"""


def build_report_pdf(markdown_text: str, title: str = "Clinical Decision Support Report",
                     subtitle: str = "", generated_on: str = None) -> bytes:
    """Render report markdown into styled PDF bytes."""
    if generated_on is None:
        generated_on = datetime.datetime.now().strftime("%d %b %Y, %H:%M")

    html_body = md.markdown(
        _strip_emoji(markdown_text or ""),
        extensions=["extra", "sane_lists"],
    )
    sub = f"{subtitle} &nbsp;·&nbsp; " if subtitle else ""
    html = _TEMPLATE.format(title=title, subtitle=sub, generated_on=generated_on, content=html_body)

    buffer = BytesIO()
    result = pisa.CreatePDF(src=html, dest=buffer, encoding="utf-8")
    if result.err:
        raise RuntimeError("Failed to render report PDF")
    return buffer.getvalue()
